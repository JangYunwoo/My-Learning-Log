/* Ex04_04.c : 관계 연산자의 사용 예 */
#include <stdio.h>

int main(void)
{
    int a = 10;
    int b = 20;

    printf("a = %d, b = %d\n", a, b);
    printf("a >  b = %d\n", a > b);
    printf("a >= b = %d\n", a >= b);
    printf("a <  b = %d\n", a < b);
    printf("a <= b = %d\n", a <= b);
    printf("a == b = %d\n", a == b);
    printf("a != b = %d\n", a != b);

    return 0;
}